//! Shadow runs (roadmap 7.4): run a command once per hypothesis, a hypothesis being a set of
//! proposed file contents laid over the server workspace.
//!
//! On Linux with unprivileged user namespaces every hypothesis gets an overlay mount of the
//! workspace copy *at the workspace's own path*: cargo, go and the other build tools see the
//! same absolute paths, so their fingerprints and the warm `target/` stay valid, everything a
//! hypothesis writes lands in its own upper directory, and the workspace copy is never
//! modified. Hypotheses run in parallel, each in its own mount namespace that disappears with
//! its process tree. Without user namespaces (macOS, kernels that restrict them) hypotheses run
//! one after another in place and the touched files are restored afterwards.
//!
//! Both modes apply a hypothesis the same way or refuse it before anything is staged or
//! written (#440): every path is relative, free of control characters and proposed once, no
//! proposed path lies inside another, the existing parents of a path are real directories (not
//! symlinks, which the in-place mode would write through), and a proposal replaces or deletes
//! a regular file or a symlink itself, never a directory, a special file or a link's target.

