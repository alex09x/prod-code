    /// `sccache_client_side` with exactly these variables and nothing from the process.
    fn verdict(
        vars: &[(&str, &str)],
        workspace: &Path,
        files: &[FileDelta],
    ) -> std::result::Result<(), String> {
        let var = |key: &str| {
            vars.iter()
                .rev()
                .find(|(k, _)| *k == key)
                .map(|(_, v)| OsString::from(v))
        };
        sccache_client_side(&var, workspace, files)
    }

