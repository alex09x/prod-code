enum Ending {
    Exited(Option<std::process::ExitStatus>),
    TimedOut,
    Cancelled,
}

/// Spawns `cmd`, keeps the tail of its output, enforces the timeout and the cancel signal.
async fn run_child(
    mut cmd: tokio::process::Command,
    job: &Job,
    mut cancel: tokio::sync::watch::Receiver<bool>,
) -> ShadowHypothesisResult {
    // The cluster's token is not the command's to see or send (#402).
    for var in prod_code_protocol::transport::AUTH_TOKEN_VARS {
        cmd.env_remove(var);
    }
    cmd.stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .kill_on_drop(true);
    // Own process group, so the timeout and a client disconnect take down the whole tree.
    #[cfg(unix)]
    cmd.process_group(0);
    let start = Instant::now();
    let mut child = match cmd.spawn() {
        Ok(child) => child,
        Err(e) => return failed(&job.name, format!("failed to start: {e}")),
    };
    let tail = Arc::new(Mutex::new(TailBuffer::new(job.tail_limit)));
    let mut readers = Vec::new();
    if let Some(out) = child.stdout.take() {
        readers.push(spawn_reader(out, Arc::clone(&tail)));
    }
    if let Some(err) = child.stderr.take() {
        readers.push(spawn_reader(err, Arc::clone(&tail)));
    }
    let ending = tokio::select! {
        status = child.wait() => Ending::Exited(status.ok()),
        _ = tokio::time::sleep(job.timeout) => Ending::TimedOut,
        _ = cancel.changed() => Ending::Cancelled,
    };
    let (status, timed_out, error) = match ending {
        Ending::Exited(status) => (status, false, None),
        Ending::TimedOut => {
            crate::kill_exec_tree(&mut child);
            (child.wait().await.ok(), true, None)
        }
        Ending::Cancelled => {
            crate::kill_exec_tree(&mut child);
            (
                child.wait().await.ok(),
                false,
                Some("cancelled: the client left".to_string()),
            )
        }
    };
    for reader in readers {
        let _ = reader.await;
    }
    let tail = tail.lock().unwrap_or_else(|e| e.into_inner());
    ShadowHypothesisResult {
        name: job.name.clone(),
        exit_code: status.and_then(|s| s.code()),
        duration_ms: start.elapsed().as_millis() as u64,
        timed_out,
        error,
        output_tail: Some(tail.bytes().to_vec()),
        output_len: tail.total,
    }
}

fn spawn_reader<R>(mut reader: R, tail: Arc<Mutex<TailBuffer>>) -> tokio::task::JoinHandle<()>
where
    R: tokio::io::AsyncRead + Unpin + Send + 'static,
{
    tokio::spawn(async move {
        let mut buf = vec![0u8; 16 * 1024];
        loop {
            match reader.read(&mut buf).await {
                Ok(0) | Err(_) => break,
                Ok(n) => tail
                    .lock()
                    .unwrap_or_else(|e| e.into_inner())
                    .push(&buf[..n]),
            }
        }
    })
}

/// Why an overlay hypothesis must not run, or `None`. An sccache daemon started outside the
/// hypothesis's mount namespace compiles against the real workspace, so sccache has to stay in
/// client-side mode, where the wrapper process inside the namespace compiles (#426).
fn check_isolation_conflicts(job: &Job) -> Option<String> {
    let var = |key: &str| effective_var(&job.env, key);
    sccache_client_side(&var, &job.workspace, &job.files)
        .err()
        .map(|why| format!("cannot run an overlay shadow: {why}"))
}

/// A variable as the overlay command sees it: the request's env wins over the gateway's, and
/// `SCCACHE_CLIENT_SIDE` is the `1` that `run_overlay` sets unless the request overrides it.
fn effective_var(env: &[(String, String)], key: &str) -> Option<OsString> {
    if let Some((_, value)) = env.iter().rev().find(|(k, _)| k == key) {
        return Some(value.into());
    }
    if key == "SCCACHE_CLIENT_SIDE" {
        return Some("1".into());
    }
    std::env::var_os(key)
}

/// `Ok` when an sccache client started with these variables compiles in client-side mode,
/// resolved as sccache 0.17 `Config::load` does: a non-empty `SCCACHE_CLIENT_SIDE` wins over
/// the config file's `client_side_mode`, and the mode is off while `SCCACHE_LOG` is set or the
/// config file names `dist.scheduler_url`. Distributed compilation is configured only in that
/// file, never through the environment.
fn sccache_client_side(
    var: &dyn Fn(&str) -> Option<OsString>,
    workspace: &Path,
    files: &[FileDelta],
) -> std::result::Result<(), String> {
    // sccache reads the variable with `env::var(..).ok()` and ignores an empty value.
    let from_env = match var("SCCACHE_CLIENT_SIDE")
        .and_then(|v| v.into_string().ok())
        .filter(|v| !v.is_empty())
    {
        None => None,
        Some(v) => match v.to_lowercase().as_str() {
            "true" | "on" | "1" => Some(true),
            "false" | "off" | "0" => {
                return Err(
                    "SCCACHE_CLIENT_SIDE turns sccache's client-side mode off, and \
                            sccache would compile in its daemon outside the hypothesis's \
                            mount namespace"
                        .to_string(),
                );
            }
            _ => {
                return Err(
                    "SCCACHE_CLIENT_SIDE is not one of true, on, 1 (sccache rejects \
                            any value other than true, on, 1, false, off, 0)"
                        .to_string(),
                );
            }
        },
    };
    if var("SCCACHE_LOG").is_some() {
        return Err(
            "SCCACHE_LOG is set, and sccache turns client-side mode off while it logs; \
                    unset it for shadow runs"
                .to_string(),
        );
    }
    let path = sccache_config_path(var)?;
    let (scheduler, from_file) = match sccache_config_content(&path, workspace, files)? {
        Some(bytes) => parse_sccache_config(&path, &bytes)?,
        None => (false, false),
    };
    if scheduler {
        return Err(format!(
            "the sccache config {} sets dist.scheduler_url; distributed compilation runs \
             outside the hypothesis's mount namespace and is not supported in shadow runs",
            path.display()
        ));
    }
    if !from_env.unwrap_or(from_file) {
        return Err(format!(
            "sccache's client-side mode is off: SCCACHE_CLIENT_SIDE is empty and the config {} \
             does not set client_side_mode = true",
            path.display()
        ));
    }
    Ok(())
}

/// The config file sccache reads: `SCCACHE_CONF`, otherwise the Linux config directory of
/// the `directories` crate (`$XDG_CONFIG_HOME` when absolute, else `$HOME/.config`).
fn sccache_config_path(
    var: &dyn Fn(&str) -> Option<OsString>,
) -> std::result::Result<PathBuf, String> {
    if let Some(conf) = var("SCCACHE_CONF") {
        let path = PathBuf::from(conf);
        if !path.is_absolute() {
            return Err(
                "SCCACHE_CONF must be an absolute path in shadow runs: sccache \
                        resolves a relative one against each compiler's working directory"
                    .to_string(),
            );
        }
        return Ok(path);
    }
    let config_home = var("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .filter(|p| p.is_absolute())
        .or_else(|| {
            var("HOME")
                .filter(|h| !h.is_empty())
                .map(|h| PathBuf::from(h).join(".config"))
        })
        .ok_or(
            "cannot locate the sccache config: none of SCCACHE_CONF, XDG_CONFIG_HOME and \
                HOME is set",
        )?;
    Ok(config_home.join("sccache").join("config"))
}

/// The config file's bytes as the hypothesis sees them (`None`: no file). The path is followed
/// through `..` and symlinks in the hypothesis's own view, so an alias such as
/// `ws/ci/../sccache.toml` or a symlink from outside into the workspace reads the proposed file
/// the overlay command would read (#426).
fn sccache_config_content(
    path: &Path,
    workspace: &Path,
    files: &[FileDelta],
) -> std::result::Result<Option<Vec<u8>>, String> {
    let unreadable =
        |why: &str| format!("cannot read the sccache config {}: {why}", path.display());
    let view = HypothesisView::new(workspace, files);
    let (physical, node) = view.resolve(path, true).map_err(|why| unreadable(&why))?;
    match node {
        Node::Missing => Ok(None),
        Node::Proposed(bytes) => Ok(Some(bytes.to_vec())),
        Node::Disk => match std::fs::read(&physical) {
            Ok(bytes) => Ok(Some(bytes)),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(unreadable(&e.kind().to_string())),
        },
        Node::Dir { .. } => Err(unreadable("is a directory")),
        Node::Link(_) => Err(unreadable("is a symbolic link")),
    }
}

/// Symlinks followed while resolving one path before giving up, as Linux does (`ELOOP`).
const MAX_SYMLINKS: usize = 40;

/// What a path is in the hypothesis's mount namespace.
enum Node<'a> {
    Missing,
    /// `upper_only`: a staged directory that hides a non-directory below it, so the workspace
    /// copy contributes nothing under it.
    Dir {
        upper_only: bool,
    },
    Link(PathBuf),
    Proposed(&'a [u8]),
    Disk,
}

enum Step {
    Root,
    Up,
    Name(OsString),
}

fn steps(path: &Path) -> Vec<Step> {
    path.components()
        .filter_map(|c| match c {
            std::path::Component::Prefix(_) | std::path::Component::RootDir => Some(Step::Root),
            std::path::Component::CurDir => None,
            std::path::Component::ParentDir => Some(Step::Up),
            std::path::Component::Normal(name) => Some(Step::Name(name.to_os_string())),
        })
        .collect()
}

/// The filesystem as an overlay hypothesis sees it: at the workspace path, the proposed files
/// (staged as regular files, so one replaces a symlink rather than writing through it) over the
/// workspace copy, minus the deletions the run script applies after mounting; everywhere else,
/// the gateway's own filesystem. It models only hypotheses `check_files` accepted, which is
/// checked first in `run_overlay`: no parent symlinks, no duplicate or nested proposals.
struct HypothesisView<'a> {
    /// Where the overlay is mounted: the workspace path with its symlinks resolved.
    workspace: PathBuf,
    proposed: Vec<(PathBuf, &'a [u8])>,
    /// Physical paths `rm -f` removes, in the view without symlinks.
    deleted: Vec<PathBuf>,
}

impl<'a> HypothesisView<'a> {
    fn new(workspace: &Path, files: &'a [FileDelta]) -> Self {
        let workspace =
            std::fs::canonicalize(workspace).unwrap_or_else(|_| workspace.to_path_buf());
        let mut view = Self {
            workspace,
            proposed: Vec::new(),
            deleted: Vec::new(),
        };
        let mut deletions = Vec::new();
        for file in files {
            // An invalid path fails staging, so the command never runs.
            let Some(rel) = safe_relative(&file.relative_path) else {
                continue;
            };
            match &file.content {
                Some(bytes) => view.proposed.push((rel, bytes.as_slice())),
                None => deletions.push(rel),
            }
        }
        // Each `rm -f` removes the last component of its path itself, not what a symlink there
        // points to.
        for rel in deletions {
            let path = view.workspace.join(rel);
            match view.resolve(&path, false) {
                Ok((_, Node::Missing)) | Err(_) => {}
                Ok((target, _)) => view.deleted.push(target),
            }
        }
        view
    }

    /// Follows an absolute path component by component as the kernel does inside the
    /// namespace, through `..` and symlinks (the last one only with `follow_last`), and returns
    /// the physical path reached and what is there.
    fn resolve(
        &self,
        path: &Path,
        follow_last: bool,
    ) -> std::result::Result<(PathBuf, Node<'a>), String> {
        if !path.is_absolute() {
            return Err("it is not an absolute path".to_string());
        }
        let mut pending = steps(path);
        pending.reverse();
        let mut cur = PathBuf::from("/");
        // One entry per component of `cur`: whether it is an upper-only directory.
        let mut upper_only: Vec<bool> = Vec::new();
        let mut links = 0;
        while let Some(step) = pending.pop() {
            let name = match step {
                Step::Root => {
                    cur = PathBuf::from("/");
                    upper_only.clear();
                    continue;
                }
                Step::Up => {
                    if cur.pop() {
                        upper_only.pop();
                    }
                    continue;
                }
                Step::Name(name) => name,
            };
            let next = cur.join(&name);
            let last = pending.is_empty();
            match self.node(&next, upper_only.last().copied().unwrap_or(false))? {
                Node::Dir { upper_only: hidden } => {
                    cur = next;
                    upper_only.push(hidden);
                }
                Node::Link(target) if follow_last || !last => {
                    links += 1;
                    if links > MAX_SYMLINKS {
                        return Err("too many levels of symbolic links".to_string());
                    }
                    pending.extend(steps(&target).into_iter().rev());
                }
                node if last => return Ok((next, node)),
                Node::Missing => return Ok((next, Node::Missing)),
                _ => return Err("a component of the path is not a directory".to_string()),
            }
        }
        let hidden = upper_only.last().copied().unwrap_or(false);
        Ok((cur, Node::Dir { upper_only: hidden }))
    }

    /// What `path`, whose parent is a directory of the view without symlinks, is. `upper_only`
    /// says the parent is a staged directory that hides the workspace copy.
    fn node(&self, path: &Path, upper_only: bool) -> std::result::Result<Node<'a>, String> {
        if self.deleted.iter().any(|d| path.starts_with(d)) {
            return Ok(Node::Missing);
        }
        if let Ok(rel) = path.strip_prefix(&self.workspace) {
            // Staged in order, so the last copy of a path wins.
            if let Some((_, bytes)) = self.proposed.iter().rev().find(|(p, _)| p == rel) {
                return Ok(Node::Proposed(bytes));
            }
            if self.proposed.iter().any(|(p, _)| p.starts_with(rel)) {
                // A staged directory merges with a directory below it and hides anything else.
                let merged =
                    !upper_only && std::fs::symlink_metadata(path).is_ok_and(|m| m.is_dir());
                return Ok(Node::Dir {
                    upper_only: !merged,
                });
            }
            if upper_only {
                return Ok(Node::Missing);
            }
        }
        match std::fs::symlink_metadata(path) {
            Ok(m) if m.file_type().is_symlink() => std::fs::read_link(path)
                .map(Node::Link)
                .map_err(|e| e.kind().to_string()),
            Ok(m) if m.is_dir() => Ok(Node::Dir { upper_only: false }),
            Ok(_) => Ok(Node::Disk),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Node::Missing),
            Err(e) => Err(e.kind().to_string()),
        }
    }
}

/// `(dist.scheduler_url is set, client_side_mode)` from a config file: JSON when its extension
/// is `json`, TOML otherwise, as sccache decides. Parser messages are not passed on because
/// they quote the file, which can hold cache credentials.
fn parse_sccache_config(path: &Path, bytes: &[u8]) -> std::result::Result<(bool, bool), String> {
    let invalid = |what: &str| format!("the sccache config {} {what}", path.display());
    let text = std::str::from_utf8(bytes).map_err(|_| invalid("is not UTF-8 text"))?;
    let value: serde_json::Value = if path.extension().is_some_and(|e| e == "json") {
        serde_json::from_str(text).map_err(|_| invalid("is not valid JSON"))?
    } else {
        toml::from_str::<toml::Table>(text)
            .ok()
            .and_then(|table| serde_json::to_value(table).ok())
            .ok_or_else(|| invalid("is not valid TOML"))?
    };
    let root = value.as_object().ok_or_else(|| invalid("is not a table"))?;
    let scheduler = match root.get("dist") {
        None => false,
        Some(serde_json::Value::Object(dist)) => {
            dist.get("scheduler_url").is_some_and(|url| !url.is_null())
        }
        Some(_) => return Err(invalid("has a `dist` that is not a table")),
    };
    let client_side = match root.get("client_side_mode") {
        None => false,
        Some(serde_json::Value::Bool(on)) => *on,
        Some(_) => return Err(invalid("has a `client_side_mode` that is not a boolean")),
    };
    Ok((scheduler, client_side))
}

/// Runs one hypothesis as an overlay shadow: its files go to a fresh upper directory, the
/// command runs in a user + mount namespace where the workspace path is the overlay.
pub async fn run_overlay(
    job: Job,
    cancel: tokio::sync::watch::Receiver<bool>,
) -> ShadowHypothesisResult {
    if let Err(why) = check_files(&job.workspace, &job.files) {
        return failed(&job.name, format!("invalid hypothesis: {why}"));
    }
    if let Some(err) = check_isolation_conflicts(&job) {
        tracing::info!(hypothesis = %job.name, reason = %err, "🌓 [SHADOW] hypothesis refused");
        return failed(&job.name, err);
    }
    let dir = job
        .shadow_root
        .join(dir_name(&job.workspace, &job.name, job.nonce));
    let upper = dir.join("upper");
    let work = dir.join("work");
    let delete_list = dir.join("delete.txt");
    let script = dir.join("run.sh");
    let staged = (|| -> Result<()> {
        std::fs::create_dir_all(&upper)?;
        std::fs::create_dir_all(&work)?;
        let deleted = stage_upper(&upper, &job.files)?;
        let mut list = String::new();
        for path in deleted {
            list.push_str(&path.to_string_lossy());
            list.push('\n');
        }
        std::fs::write(&delete_list, list)?;
        std::fs::write(&script, RUN_SCRIPT)?;
        Ok(())
    })();
    if let Err(e) = staged {
        remove_shadow_dir(&dir);
        return failed(&job.name, format!("cannot stage hypothesis: {e:#}"));
    }
    let mut cmd = tokio::process::Command::new("unshare");
    cmd.args(["-Urm", "--propagation", "private", "sh"])
        .arg(&script)
        .args(&job.argv)
        // Ensure sccache compiles in the client process inside the mount namespace (#426);
        // a request may override it, and `check_isolation_conflicts` has judged the result.
        .env("SCCACHE_CLIENT_SIDE", "1")
        .envs(job.env.iter().map(|(k, v)| (k.as_str(), v.as_str())))
        // Set after the request's env: the run script's own variables are not its to replace.
        .env("SHADOW_LOWER", &job.workspace)
        .env("SHADOW_UPPER", &upper)
        .env("SHADOW_WORK", &work)
        .env("SHADOW_DELETE", &delete_list)
        .env("SHADOW_SUBDIR", &job.subdir)
        .current_dir(&job.workspace);
    let result = run_child(cmd, &job, cancel).await;
    // The upper directory can hold a whole incremental build; remove it off the response path.
    tokio::task::spawn_blocking(move || remove_shadow_dir(&dir));
    result
}

/// Runs one hypothesis in place: writes its files into the workspace copy, runs the command,
/// then puts back every path that is still what the hypothesis left there (a file someone
/// else changed meanwhile is left alone and logged).
pub async fn run_in_place(
    job: Job,
    cancel: tokio::sync::watch::Receiver<bool>,
) -> ShadowHypothesisResult {
    let paths = match check_files(&job.workspace, &job.files) {
        Ok(paths) => paths,
        Err(why) => return failed(&job.name, format!("invalid hypothesis: {why}")),
    };
    let mut applied = InPlace {
        workspace: job.workspace.clone(),
        touched: Vec::new(),
        created: Vec::new(),
    };
    for (rel, file) in paths.iter().zip(&job.files) {
        if let Err(e) = applied.apply(rel, file) {
            applied.restore();
            let path = job.workspace.join(rel);
            return failed(&job.name, format!("cannot write {}: {e}", path.display()));
        }
    }
    let mut cmd = tokio::process::Command::new("sh");
    cmd.args(["-c", "exec \"$@\" 2>&1", "sh"])
        .args(&job.argv)
        .envs(job.env.iter().map(|(k, v)| (k.as_str(), v.as_str())))
        .current_dir(job.workspace.join(&job.subdir));
    let result = run_child(cmd, &job, cancel).await;
    applied.restore();
    result
}

/// What was at a path before the in-place mode replaced or deleted it.
enum Original {
    Missing,
    File {
        bytes: Vec<u8>,
        permissions: std::fs::Permissions,
        modified: Option<std::time::SystemTime>,
    },
    Link(PathBuf),
}

/// A path the in-place mode touched, and what the hypothesis left there (None: deleted).
struct Touched {
    path: PathBuf,
    original: Original,
    written: Option<Vec<u8>>,
}

/// The in-place changes of one hypothesis. An existing file or symlink is removed and a new
/// file created in its place, so nothing is written through a symlink or into an inode that a
/// hard link outside the workspace shares; restoring does the same in reverse.
struct InPlace {
    workspace: PathBuf,
    touched: Vec<Touched>,
    /// Directories created for proposed files, removed again on restore.
    created: Vec<PathBuf>,
}

impl InPlace {
    /// Applies one file whose path `check_files` accepted.
    fn apply(&mut self, rel: &Path, file: &FileDelta) -> std::io::Result<()> {
        let path = self.workspace.join(rel);
        if file.content.is_some() {
            let mut dir = self.workspace.clone();
            for component in rel.parent().into_iter().flat_map(Path::components) {
                dir.push(component);
                match std::fs::create_dir(&dir) {
                    Ok(()) => self.created.push(dir.clone()),
                    // A real directory: `check_files` refused anything else.
                    Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {}
                    Err(e) => return Err(e),
                }
            }
        }
        let original = match std::fs::symlink_metadata(&path) {
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Original::Missing,
            Err(e) => return Err(e),
            Ok(meta) if meta.file_type().is_symlink() => Original::Link(std::fs::read_link(&path)?),
            Ok(meta) => Original::File {
                bytes: std::fs::read(&path)?,
                permissions: meta.permissions(),
                modified: meta.modified().ok(),
            },
        };
        if !matches!(original, Original::Missing) {
            std::fs::remove_file(&path)?;
        }
        self.touched.push(Touched {
            path: path.clone(),
            original,
            written: file.content.clone(),
        });
        if let Some(bytes) = &file.content {
            // The same modes the overlay stages: 0755 when executable, else the umask default.
            #[cfg(unix)]
            let permissions = file.is_executable.then(|| {
                use std::os::unix::fs::PermissionsExt;
                std::fs::Permissions::from_mode(0o755)
            });
            #[cfg(not(unix))]
            let permissions = None;
            create_file(&path, bytes, permissions, None)?;
        }
        Ok(())
    }

    fn restore(self) {
        for touched in self.touched.iter().rev() {
            if let Err(why) = self.restore_one(touched) {
                tracing::warn!(path = %touched.path.display(), "shadow run: {why}");
            }
        }
        for dir in self.created.iter().rev() {
            if let Err(e) = std::fs::remove_dir(dir) {
                tracing::warn!(
                    path = %dir.display(),
                    error = %e,
                    "shadow run: could not remove a directory the hypothesis created"
                );
            }
        }
    }

    fn restore_one(&self, touched: &Touched) -> std::result::Result<(), String> {
        // The command may have replaced a parent with a symlink; never restore through one.
        if !self.real_parents(&touched.path) {
            return Err("a parent is no longer a real directory; not restored".to_string());
        }
        let current = std::fs::symlink_metadata(&touched.path);
        let unchanged = match (&touched.written, &current) {
            (None, Err(e)) => e.kind() == std::io::ErrorKind::NotFound,
            (Some(bytes), Ok(meta)) => {
                meta.is_file() && std::fs::read(&touched.path).is_ok_and(|b| &b == bytes)
            }
            _ => false,
        };
        if !unchanged {
            return Err("file changed while the hypothesis ran; not restored".to_string());
        }
        let restored = (|| -> std::io::Result<()> {
            if touched.written.is_some() {
                std::fs::remove_file(&touched.path)?;
            }
            match &touched.original {
                Original::Missing => Ok(()),
                Original::File {
                    bytes,
                    permissions,
                    modified,
                } => create_file(&touched.path, bytes, Some(permissions.clone()), *modified),
                #[cfg(unix)]
                Original::Link(target) => std::os::unix::fs::symlink(target, &touched.path),
                #[cfg(not(unix))]
                Original::Link(_) => Err(std::io::Error::other("symlinks need unix")),
            }
        })();
        restored.map_err(|e| format!("could not restore file: {e}"))
    }

    /// Whether every directory between the workspace and `path` is a directory, not a symlink.
    fn real_parents(&self, path: &Path) -> bool {
        let Some(rel) = path
            .strip_prefix(&self.workspace)
            .ok()
            .and_then(Path::parent)
        else {
            return false;
        };
        let mut dir = self.workspace.clone();
        rel.components().all(|component| {
            dir.push(component);
            std::fs::symlink_metadata(&dir).is_ok_and(|m| m.is_dir())
        })
    }
}

/// Creates a new file (failing if anything, a symlink included, is at `path`) with `bytes`,
/// and optionally the given permissions and modification time.
fn create_file(
    path: &Path,
    bytes: &[u8],
    permissions: Option<std::fs::Permissions>,
    modified: Option<std::time::SystemTime>,
) -> std::io::Result<()> {
    use std::io::Write;
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)?;
    file.write_all(bytes)?;
    if let Some(permissions) = permissions {
        file.set_permissions(permissions)?;
    }
    if let Some(modified) = modified {
        file.set_modified(modified)?;
    }
    Ok(())
}

fn default_parallel() -> usize {
    std::thread::available_parallelism()
        .map(|n| (n.get() / 8).max(1))
        .unwrap_or(1)
}

/// Handles a `ShadowRunRequest` on a client connection: runs every hypothesis (in parallel as
/// overlays where the node supports them), answers pings meanwhile, kills everything if the
/// client leaves, and finishes with one `ShadowRunResponse`.
pub async fn run_shadow(
    state: &crate::ServerState,
    framed: &mut Framed<TcpStream, ProdCodeCodec>,
    req: ShadowRunRequest,
) -> Result<()> {
    let workspace = crate::workspace::server_workspace_path(
        &state.storage_root,
        &req.client_workspace_root,
        req.base_workspace_name.as_deref(),
    );
    let workspace_str = workspace.to_string_lossy().to_string();
    let refuse = |error: String| ShadowRunResponse {
        server_workspace_root: workspace_str.clone(),
        mode: String::new(),
        results: Vec::new(),
        error: Some(error),
    };
    let refusal = if !workspace.is_dir() {
        Some(format!(
            "workspace {workspace_str} is not synced to this gateway"
        ))
    } else if req.command.is_empty() {
        Some("empty command".to_string())
    } else if req.hypotheses.is_empty() {
        Some("no hypotheses".to_string())
    } else {
        let mut seen = std::collections::HashSet::new();
        req.hypotheses
            .iter()
            .find(|h| h.name.trim().is_empty() || !seen.insert(h.name.as_str()))
            .map(|h| format!("hypothesis name {:?} is empty or repeated", h.name))
    };
    if let Some(error) = refusal {
        framed
            .send(WireMessage::ShadowRunResponse(refuse(error)))
            .await?;
        return Ok(());
    }
    let subdir = match req.subdir.as_deref() {
        Some(sub)
            if !sub.is_empty()
                && !sub.starts_with('/')
                && !sub.split('/').any(|c| c == "..")
                && workspace.join(sub).is_dir() =>
        {
            sub.to_string()
        }
        _ => String::new(),
    };
    let timeout = Duration::from_secs(if req.timeout_secs == 0 {
        DEFAULT_TIMEOUT_SECS
    } else {
        req.timeout_secs
    });
    let tail_limit = if req.tail_bytes == 0 {
        DEFAULT_TAIL_BYTES
    } else {
        req.tail_bytes
    };
    let overlay_reason = tokio::task::spawn_blocking(overlay_unavailable)
        .await
        .unwrap_or(Some("overlay probe failed"));
    let overlay = overlay_reason.is_none();
    let mode = if overlay { "overlay" } else { "in-place" };
    let parallel = if !overlay {
        1
    } else if req.parallel == 0 {
        default_parallel()
    } else {
        req.parallel
    };
    if let Some(reason) = overlay_reason {
        tracing::info!(
            reason,
            "🌓 [SHADOW] overlay shadows unavailable; running in place"
        );
    }
    if overlay {
        std::fs::create_dir_all(&state.shadow_root)
            .with_context(|| format!("cannot create {}", state.shadow_root.display()))?;
    }
    let names: Vec<String> = req.hypotheses.iter().map(|h| h.name.clone()).collect();
    let count = names.len();
    tracing::info!(
        workspace = %workspace_str,
        command = %req.command.join(" "),
        hypotheses = count,
        mode,
        parallel,
        "🌓 [SHADOW] started"
    );
    let start = Instant::now();
    let (cancel_tx, cancel_rx) = tokio::sync::watch::channel(false);
    let semaphore = Arc::new(tokio::sync::Semaphore::new(parallel));
    let nonce = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0);
    let mut handles = Vec::with_capacity(count);
    for hypothesis in req.hypotheses {
        let job = Job {
            name: hypothesis.name,
            files: hypothesis.files,
            argv: req.command.clone(),
            env: req.env.clone(),
            timeout,
            tail_limit,
            workspace: workspace.clone(),
            subdir: subdir.clone(),
            shadow_root: state.shadow_root.clone(),
            nonce,
        };
        let semaphore = Arc::clone(&semaphore);
        let cancel = cancel_rx.clone();
        handles.push(tokio::spawn(async move {
            let _permit = semaphore.acquire_owned().await;
            if *cancel.borrow() {
                return failed(&job.name, "cancelled: the client left".to_string());
            }
            if overlay {
                run_overlay(job, cancel).await
            } else {
                run_in_place(job, cancel).await
            }
        }));
    }
    let all = futures_util::future::join_all(handles);
    tokio::pin!(all);
    let joined = loop {
        tokio::select! {
            joined = &mut all => break joined,
            incoming = framed.next() => match incoming {
                Some(Ok(WireMessage::Ping)) => framed.send(WireMessage::Pong).await?,
                Some(Ok(WireMessage::Disconnect { .. })) | None => {
                    let _ = cancel_tx.send(true);
                    let _ = (&mut all).await;
                    tracing::info!(workspace = %workspace_str, "🌓 [SHADOW] client left; hypotheses killed");
                    return Ok(());
                }
                Some(Err(e)) => {
                    let _ = cancel_tx.send(true);
                    let _ = (&mut all).await;
                    return Err(e.into());
                }
                _ => {}
            }
        }
    };
    let results: Vec<ShadowHypothesisResult> = joined
        .into_iter()
        .zip(names.iter())
        .map(|(joined, name)| {
            joined.unwrap_or_else(|e| failed(name, format!("hypothesis task failed: {e}")))
        })
        .collect();
    for result in &results {
        let mut ev = crate::metrics::Event::blank("shadow");
        ev.agent = req
            .client_agent
            .clone()
            .unwrap_or_else(|| "unknown".to_string());
        ev.host = req
            .client_host
            .clone()
            .unwrap_or_else(|| "unknown".to_string());
        ev.workspace = workspace
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default();
        ev.command = format!("{} [{}]", req.command.join(" "), result.name);
        ev.duration_ms = result.duration_ms;
        ev.exit_code = result.exit_code;
        ev.ok = result.exit_code == Some(0);
        ev.bytes = result.output_len;
        state.metrics.record(ev);
    }
    tracing::info!(
        workspace = %workspace_str,
        hypotheses = count,
        passed = results.iter().filter(|r| r.exit_code == Some(0)).count(),
        duration_ms = start.elapsed().as_millis() as u64,
        "🌓 [SHADOW] finished"
    );
    framed
        .send(WireMessage::ShadowRunResponse(ShadowRunResponse {
            server_workspace_root: workspace_str,
            mode: mode.to_string(),
            results,
            error: None,
        }))
        .await?;
    Ok(())
}

