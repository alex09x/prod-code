/// The script every overlay hypothesis runs inside its own user + mount namespace: mount the
/// overlay over the workspace path, apply deletions, then drops the namespace-root capabilities
/// before it runs the command with stderr merged. The deletion list holds one path per line,
/// which is lossless because `check_files` refuses control characters; each entry is a file or a
/// symlink, so `rm` never recurses.
const RUN_SCRIPT: &str = r#"#!/bin/sh
# Generated by prod-code for one hypothesis of a shadow run.
set -e
if ! mount -t overlay overlay -o "lowerdir=$SHADOW_LOWER,upperdir=$SHADOW_UPPER,workdir=$SHADOW_WORK" "$SHADOW_LOWER"; then
  echo "prod-code: overlay mount failed" >&2
  exit 253
fi
if [ -s "$SHADOW_DELETE" ]; then
  while IFS= read -r p; do rm -f "$SHADOW_LOWER/$p"; done < "$SHADOW_DELETE"
fi
cd "$SHADOW_LOWER/$SHADOW_SUBDIR"
exec "$SHADOW_SETPRIV" --bounding-set=-all --inh-caps=-all --ambient-caps=-all --no-new-privs "$@" 2>&1
"#;

fn is_diagnostic_error_header(line: &str) -> bool {
    let trimmed = line.trim_start();
    if let Some(rest) = trimmed.strip_prefix("error") {
        let is_code = rest.starts_with('[') && rest.contains("]:");
        let is_colon = rest.starts_with(':');
        if is_code || is_colon {
            let msg = rest.split_once(':').map_or("", |(_, m)| m.trim());
            if !msg.starts_with("could not compile")
                && !msg.starts_with("aborting due to")
                && !msg.starts_with("build failed")
            {
                return true;
            }
        }
    }
    if trimmed.contains(": error:") || trimmed.contains(" - error TS") {
        return true;
    }
    (trimmed.starts_with("---- ") && trimmed.ends_with(" stdout ----"))
        || (trimmed.starts_with("thread '") && trimmed.contains("' panicked at "))
        || trimmed.starts_with("--- FAIL: ")
        || trimmed.starts_with("FAILED ")
}

fn is_diagnostic_boundary(line: &str) -> bool {
    let trimmed = line.trim_start();
    trimmed.starts_with("warning:")
        || (trimmed.starts_with("warning[") && trimmed.contains("]:"))
        || trimmed.contains(": warning:")
        || trimmed.contains(" - warning TS")
        || is_diagnostic_error_header(line)
        || trimmed.starts_with("Compiling ")
        || trimmed.starts_with("Checking ")
        || trimmed.starts_with("Finished ")
        || trimmed.starts_with("error: could not compile")
        || trimmed.starts_with("error: aborting due to")
}

/// Keeps the last `limit` bytes of a stream, counts everything that went through, and retains
/// compiler error sections so they are not dropped when warnings exceed the tail cap (#794).
pub struct TailBuffer {
    limit: usize,
    buf: Vec<u8>,
    pub total: u64,
    retained_errors: Vec<u8>,
    line_buf: Vec<u8>,
    recording_error: bool,
}

impl TailBuffer {
    pub fn new(limit: usize) -> Self {
        Self {
            limit: limit.max(1),
            buf: Vec::new(),
            total: 0,
            retained_errors: Vec::new(),
            line_buf: Vec::new(),
            recording_error: false,
        }
    }

    pub fn push(&mut self, data: &[u8]) {
        self.total += data.len() as u64;
        self.buf.extend_from_slice(data);
        if self.buf.len() > self.limit {
            let cut = self.buf.len() - self.limit;
            self.buf.drain(..cut);
        }

        for &b in data {
            self.line_buf.push(b);
            if b == b'\n' {
                let line_str = String::from_utf8_lossy(&self.line_buf);
                if is_diagnostic_error_header(&line_str) {
                    self.recording_error = true;
                } else if self.recording_error && is_diagnostic_boundary(&line_str) {
                    self.recording_error = false;
                }

                if self.recording_error && self.retained_errors.len() < self.limit {
                    self.retained_errors.extend_from_slice(&self.line_buf);
                }
                self.line_buf.clear();
            }
        }
    }

    pub fn bytes(&self) -> &[u8] {
        &self.buf
    }

    pub fn to_output(&self) -> Vec<u8> {
        if self.total <= self.limit as u64 || self.retained_errors.is_empty() {
            return self.buf.clone();
        }
        let first_line = self
            .retained_errors
            .split(|&b| b == b'\n')
            .next()
            .unwrap_or(&[]);
        if !first_line.is_empty() && self.buf.windows(first_line.len()).any(|w| w == first_line) {
            return self.buf.clone();
        }
        let mut out = Vec::with_capacity(self.retained_errors.len() + 32 + self.buf.len());
        out.extend_from_slice(&self.retained_errors);
        if !out.ends_with(b"\n") {
            out.push(b'\n');
        }
        out.extend_from_slice(b"\n[... output truncated ...]\n");
        out.extend_from_slice(&self.buf);
        out
    }
}

/// A storage-specific shadow namespace next to the workspace storage directory. Canonical
/// aliases of one storage directory choose the same namespace, while sibling storage roots do
/// not share one.
pub fn default_root(storage_root: &Path) -> PathBuf {
    if let Ok(custom_root) = std::env::var("PROD_CODE_SHADOW_ROOT")
        && !custom_root.trim().is_empty()
    {
        return PathBuf::from(custom_root.trim());
    }
    let identity = storage_identity(storage_root);
    let label: String = identity
        .file_name()
        .unwrap_or_else(|| OsStr::new("storage"))
        .to_string_lossy()
        .chars()
        .take(32)
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.') {
                c
            } else {
                '_'
            }
        })
        .collect();
    let hash = identity
        .as_os_str()
        .as_encoded_bytes()
        .iter()
        .fold(0xcbf29ce484222325u64, |hash, byte| {
            (hash ^ u64::from(*byte)).wrapping_mul(0x100000001b3)
        });
    if let Ok(ram_env) = std::env::var("PROD_CODE_SHADOW_RAM")
        && (ram_env == "1" || ram_env.eq_ignore_ascii_case("true"))
    {
        if let Some(ram_root) = ram_shadow_root(storage_root) {
            return ram_root;
        }
    }
    identity
        .parent()
        .map(|parent| parent.join(format!(".prod-code-shadow-{label}-{hash:016x}")))
        .unwrap_or_else(|| identity.join(format!(".shadow-{hash:016x}")))
}

/// A lightweight in-memory RAM overlay root in `/dev/shm` for speculative shadow execution (Roadmap 7.4).
/// Returns `None` if `/dev/shm` does not exist or is not a directory.
pub fn ram_shadow_root(storage_root: &Path) -> Option<PathBuf> {
    let shm = Path::new("/dev/shm");
    if !shm.is_dir() {
        return None;
    }
    let identity = storage_identity(storage_root);
    let label: String = identity
        .file_name()
        .unwrap_or_else(|| OsStr::new("storage"))
        .to_string_lossy()
        .chars()
        .take(32)
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.') {
                c
            } else {
                '_'
            }
        })
        .collect();
    let hash = identity
        .as_os_str()
        .as_encoded_bytes()
        .iter()
        .fold(0xcbf29ce484222325u64, |hash, byte| {
            (hash ^ u64::from(*byte)).wrapping_mul(0x100000001b3)
        });
    Some(shm.join(format!(".prod-code-shadow-ram-{label}-{hash:016x}")))
}

fn storage_identity(storage_root: &Path) -> PathBuf {
    if let Ok(canonical) = storage_root.canonicalize() {
        return canonical;
    }
    let absolute = if storage_root.is_absolute() {
        storage_root.to_path_buf()
    } else {
        std::env::current_dir()
            .unwrap_or_else(|_| PathBuf::from("."))
            .join(storage_root)
    };
    let mut identity = PathBuf::new();
    let mut unresolved = false;
    for component in absolute.components() {
        match component {
            Component::Prefix(prefix) => identity.push(prefix.as_os_str()),
            Component::RootDir => identity.push(component.as_os_str()),
            Component::CurDir => {}
            Component::Normal(name) => {
                let candidate = identity.join(name);
                match candidate.canonicalize() {
                    Ok(canonical) => {
                        identity = canonical;
                        unresolved = false;
                    }
                    Err(_) => {
                        identity = candidate;
                        unresolved = true;
                    }
                }
            }
            Component::ParentDir if unresolved => {
                identity.pop();
                if let Ok(canonical) = identity.canonicalize() {
                    identity = canonical;
                    unresolved = false;
                }
            }
            Component::ParentDir => {
                let candidate = identity.join("..");
                match candidate.canonicalize() {
                    Ok(canonical) => identity = canonical,
                    Err(_) => {
                        identity = candidate;
                        unresolved = true;
                    }
                }
            }
        }
    }
    identity
}

/// Exclusive ownership of one shadow namespace. The lock file is never replaced or swept, so
/// canonical aliases contend on the same inode and dropping this guard releases ownership on
/// every normal return or startup error path.
pub struct ShadowRootOwner {
    root: PathBuf,
    _lock: File,
}

impl ShadowRootOwner {
    pub fn acquire(root: &Path) -> Result<Self> {
        std::fs::create_dir_all(root)
            .with_context(|| format!("cannot create shadow root {}", root.display()))?;
        let root = root
            .canonicalize()
            .with_context(|| format!("cannot resolve shadow root {}", root.display()))?;
        let lock_path = root.join(OWNERSHIP_LOCK_FILE);
        let mut options = OpenOptions::new();
        options.read(true).write(true).create(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.custom_flags(libc::O_NOFOLLOW);
        }
        let lock = options.open(&lock_path).with_context(|| {
            format!("cannot open shadow ownership lock {}", lock_path.display())
        })?;
        match lock.try_lock() {
            Ok(()) => {}
            Err(std::fs::TryLockError::WouldBlock) => bail!(
                "shadow root {} is already owned by another gateway; stop that gateway or choose a distinct --shadow-dir / PROD_CODE_SHADOW_DIR",
                root.display()
            ),
            Err(std::fs::TryLockError::Error(err)) => {
                return Err(err).with_context(|| {
                    format!(
                        "cannot lock shadow root ownership at {}",
                        lock_path.display()
                    )
                });
            }
        }
        Ok(Self { root, _lock: lock })
    }

    /// Removes abandoned hypothesis directories from this exclusively owned namespace. Other
    /// entries, including the stable ownership lock, are never touched.
    pub fn sweep(&self) -> usize {
        let Ok(entries) = std::fs::read_dir(&self.root) else {
            return 0;
        };
        let mut removed = 0;
        for entry in entries.flatten() {
            if !entry
                .file_name()
                .to_string_lossy()
                .starts_with(HYPOTHESIS_DIR_PREFIX)
                || !entry.file_type().is_ok_and(|kind| kind.is_dir())
            {
                continue;
            }
            remove_shadow_dir(&entry.path());
            removed += 1;
        }
        removed
    }
}

/// `None` when this node can run hypotheses as overlay shadows, otherwise why it cannot.
/// Probed once per process: a throw-away overlay mount inside a user namespace.
pub fn overlay_unavailable() -> Option<&'static str> {
    static PROBE: OnceLock<Option<String>> = OnceLock::new();
    PROBE.get_or_init(probe_overlay).as_deref()
}

/// The gateway's trusted `setpriv` executable. The request can replace PATH, so the run script
/// receives this absolute path after request environment variables.
fn setpriv_path() -> std::result::Result<PathBuf, String> {
    let path = std::env::var_os("PATH").ok_or_else(|| {
        "cannot find setpriv: the gateway PATH is unset; overlay shadows need setpriv to drop \
         namespace-root capabilities"
            .to_string()
    })?;
    for dir in std::env::split_paths(&path) {
        let candidate = dir.join("setpriv");
        if candidate.is_file() {
            return candidate
                .canonicalize()
                .map_err(|e| format!("cannot resolve {}: {e}", candidate.display()));
        }
    }
    Err(
        "cannot find setpriv on the gateway PATH; overlay shadows need it to drop \
         namespace-root capabilities"
            .to_string(),
    )
}

fn probe_overlay() -> Option<String> {
    if !cfg!(target_os = "linux") {
        return Some("overlay shadows need Linux (user namespaces + overlayfs)".to_string());
    }
    let setpriv = match setpriv_path() {
        Ok(path) => path,
        Err(why) => return Some(why),
    };
    let dir = std::env::temp_dir().join(format!("prod-code-shadow-probe-{}", std::process::id()));
    let (lower, upper, work, mnt) = (
        dir.join("lower"),
        dir.join("upper"),
        dir.join("work"),
        dir.join("mnt"),
    );
    let prepared = (|| -> std::io::Result<()> {
        for d in [&lower, &upper, &work, &mnt] {
            std::fs::create_dir_all(d)?;
        }
        std::fs::write(lower.join("probe"), "ok\n")
    })();
    if let Err(e) = prepared {
        return Some(format!("cannot prepare {}: {e}", dir.display()));
    }
    let script = format!(
        r#"mount -t overlay overlay -o lowerdir={l},upperdir={u},workdir={w} {m} || exit
chmod 0444 {m}/probe || exit
if ! "$SHADOW_SETPRIV" --bounding-set=-all --inh-caps=-all --ambient-caps=-all --no-new-privs \
    sh -c 'printf changed > "$1/probe" 2>/dev/null; test $? -ne 0' sh {m}; then
    echo "setpriv did not drop namespace-root file-write privileges" >&2
    exit 1
fi
test "$(cat {m}/probe)" = ok && printf 'ok\n'"#,
        l = lower.display(),
        u = upper.display(),
        w = work.display(),
        m = mnt.display()
    );
    let output = std::process::Command::new("unshare")
        .args(["-Urm", "--propagation", "private", "sh", "-c", &script])
        .env("SHADOW_SETPRIV", setpriv)
        .output();
    let verdict = match output {
        Ok(o) if o.status.success() && o.stdout == b"ok\n" => None,
        Ok(o) => Some(format!(
            "unprivileged overlay mount failed: {}",
            String::from_utf8_lossy(&o.stderr).trim()
        )),
        Err(e) => Some(format!("cannot run unshare: {e}")),
    };
    remove_shadow_dir(&dir);
    verdict
}

/// Removes a shadow directory. The overlay work directory holds entries created by the
/// namespace's root with mode 000, which the gateway's own uid cannot delete directly, so
/// the removal is retried inside a user namespace.
pub fn remove_shadow_dir(dir: &Path) {
    if !dir.exists() {
        return;
    }
    if std::fs::remove_dir_all(dir).is_ok() {
        return;
    }
    let _ = std::process::Command::new("unshare")
        .args(["-Urm", "rm", "-rf"])
        .arg(dir)
        .status();
    if dir.exists() {
        tracing::warn!(dir = %dir.display(), "could not remove shadow directory");
    }
}

/// A relative path that stays inside the workspace, or `None`. Control characters are refused:
/// the overlay's deletion list is line-based, and `name\n../outside` would otherwise become a
/// second, unchecked path there (#440).
fn safe_relative(path: &str) -> Option<PathBuf> {
    let p = Path::new(path);
    if path.is_empty() || p.is_absolute() || path.chars().any(char::is_control) {
        return None;
    }
    let mut out = PathBuf::new();
    for component in p.components() {
        match component {
            std::path::Component::Normal(s) => out.push(s),
            std::path::Component::CurDir => {}
            _ => return None,
        }
    }
    (!out.as_os_str().is_empty()).then_some(out)
}

/// The workspace-relative paths of a hypothesis's files, in order, once they are known to
/// apply the same way in the overlay and in place (see the module docs); otherwise why not.
/// Only the workspace copy is inspected, nothing is written.
fn check_files(workspace: &Path, files: &[FileDelta]) -> std::result::Result<Vec<PathBuf>, String> {
    let mut paths: Vec<PathBuf> = Vec::with_capacity(files.len());
    for file in files {
        let rel = safe_relative(&file.relative_path).ok_or_else(|| {
            format!(
                "invalid path {:?}: it must be relative, stay inside the workspace and hold \
                 no control character",
                file.relative_path
            )
        })?;
        if paths.contains(&rel) {
            return Err(format!("{rel:?} is proposed more than once"));
        }
        if let Some(other) = paths
            .iter()
            .find(|p| p.starts_with(&rel) || rel.starts_with(p))
        {
            return Err(format!(
                "{rel:?} and {other:?} are both proposed, and one lies inside the other"
            ));
        }
        paths.push(rel);
    }
    for rel in &paths {
        let mut cur = workspace.to_path_buf();
        let depth = rel.components().count();
        for (i, component) in rel.components().enumerate() {
            cur.push(component);
            let last = i + 1 == depth;
            let meta = match std::fs::symlink_metadata(&cur) {
                Ok(meta) => meta,
                // Created by the hypothesis, or a deletion of nothing: the same in both modes.
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => break,
                Err(e) => return Err(format!("cannot inspect {cur:?}: {e}")),
            };
            let kind = meta.file_type();
            if !last {
                if kind.is_symlink() {
                    return Err(format!(
                        "a parent of {rel:?} is a symbolic link; shadow runs do not write \
                         through symlinked directories"
                    ));
                }
                if !kind.is_dir() {
                    return Err(format!("a parent of {rel:?} is not a directory"));
                }
            } else if kind.is_dir() {
                return Err(format!(
                    "{rel:?} is a directory; shadow runs replace or delete files only"
                ));
            } else if !kind.is_file() && !kind.is_symlink() {
                return Err(format!(
                    "{rel:?} is neither a regular file nor a symbolic link"
                ));
            }
        }
    }
    Ok(paths)
}

/// Writes the hypothesis's files into the overlay upper directory (they shadow the workspace
/// copy once mounted) and returns the paths to delete inside the mount.
fn stage_upper(upper: &Path, files: &[FileDelta]) -> Result<Vec<PathBuf>> {
    let mut deleted = Vec::new();
    for file in files {
        let rel = safe_relative(&file.relative_path)
            .with_context(|| format!("invalid path {:?}", file.relative_path))?;
        match &file.content {
            Some(bytes) => {
                let dest = upper.join(&rel);
                if let Some(parent) = dest.parent() {
                    std::fs::create_dir_all(parent)?;
                }
                std::fs::write(&dest, bytes)?;
                #[cfg(unix)]
                if file.is_executable {
                    use std::os::unix::fs::PermissionsExt;
                    std::fs::set_permissions(&dest, std::fs::Permissions::from_mode(0o755))?;
                }
            }
            None => deleted.push(rel),
        }
    }
    Ok(deleted)
}

fn dir_name(workspace: &Path, hypothesis: &str, nonce: u64) -> String {
    let ws = workspace
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_else(|| "workspace".to_string());
    let safe: String = hypothesis
        .chars()
        .take(48)
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.') {
                c
            } else {
                '_'
            }
        })
        .collect();
    format!("{HYPOTHESIS_DIR_PREFIX}{ws}--{safe}-{nonce:x}")
}

fn failed(name: &str, error: String) -> ShadowHypothesisResult {
    ShadowHypothesisResult {
        name: name.to_string(),
        exit_code: None,
        duration_ms: 0,
        timed_out: false,
        error: Some(error),
        output_tail: None,
        output_len: 0,
    }
}

