    /// A workspace and a sibling directory holding a sentinel, both in one disposable
    /// directory: `(root, workspace, outside)`.
    fn workspace_with_sibling() -> (tempfile::TempDir, PathBuf, PathBuf) {
        let root = tempfile::tempdir().unwrap();
        let ws = root.path().join("ws");
        let outside = root.path().join("outside");
        std::fs::create_dir_all(&ws).unwrap();
        std::fs::create_dir_all(&outside).unwrap();
        std::fs::write(outside.join("sentinel"), "keep\n").unwrap();
        (root, ws, outside)
    }

    fn sentinel(outside: &Path) -> Option<String> {
        std::fs::read_to_string(outside.join("sentinel")).ok()
    }

    /// Every entry below `root` without following symlinks: type, mode, symlink target, and
    /// for files the content and modification time.
    fn snapshot(root: &Path) -> Vec<(PathBuf, String)> {
        use std::os::unix::fs::MetadataExt;
        let mut out = Vec::new();
        let mut stack = vec![root.to_path_buf()];
        while let Some(dir) = stack.pop() {
            for entry in std::fs::read_dir(&dir).unwrap() {
                let path = entry.unwrap().path();
                let m = std::fs::symlink_metadata(&path).unwrap();
                let what = if m.file_type().is_symlink() {
                    format!("link -> {}", std::fs::read_link(&path).unwrap().display())
                } else if m.is_dir() {
                    stack.push(path.clone());
                    format!("dir {:o}", m.mode())
                } else {
                    format!(
                        "file {:o} mtime={}.{} {:?}",
                        m.mode(),
                        m.mtime(),
                        m.mtime_nsec(),
                        String::from_utf8_lossy(&std::fs::read(&path).unwrap())
                    )
                };
                out.push((path.strip_prefix(root).unwrap().to_path_buf(), what));
            }
        }
        out.sort();
        out
    }

    /// Runs the hypothesis as an overlay shadow where the node supports it, then in place, and
    /// hands each result to `check` right after its run.
    async fn in_both_modes(make: impl Fn() -> Job, check: impl Fn(&str, ShadowHypothesisResult)) {
        let (_tx, rx) = tokio::sync::watch::channel(false);
        match overlay_unavailable() {
            None => check("overlay", run_overlay(make(), rx.clone()).await),
            Some(reason) => eprintln!("overlay mode skipped: {reason}"),
        }
        check("in-place", run_in_place(make(), rx).await);
    }

